-- Espace responsables de clubs.
-- À exécuter une seule fois dans Supabase > SQL Editor après 01_schema.sql et 02_rls_policies.sql.
-- Le mot de passe reste géré exclusivement par Supabase Auth et n'est jamais stocké dans ces tables.

create table if not exists public.club_profiles (
  id text primary key,
  name text not null,
  category text not null,
  tagline text not null,
  description text not null,
  founded_label text,
  recruitment_label text,
  contact_label text,
  contact_url text,
  objectives text[] not null default '{}',
  status text not null default 'active' check (status in ('active', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.club_managers (
  user_id uuid not null references auth.users(id) on delete cascade,
  club_id text not null references public.club_profiles(id) on delete cascade,
  manager_role text not null default 'manager' check (manager_role in ('manager', 'president')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (user_id, club_id)
);

create table if not exists public.club_events (
  id uuid primary key default gen_random_uuid(),
  club_id text not null references public.club_profiles(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete restrict default auth.uid(),
  title text not null check (char_length(title) between 3 and 180),
  description text not null check (char_length(description) between 10 and 1200),
  location text not null,
  event_type text not null default 'Atelier',
  starts_at timestamptz not null,
  ends_at timestamptz,
  capacity integer check (capacity is null or capacity > 0),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at is null or ends_at >= starts_at)
);

create table if not exists public.club_event_registrations (
  event_id uuid not null references public.club_events(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  status text not null default 'registered' check (status in ('registered', 'cancelled')),
  attended boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (event_id, user_id)
);

create table if not exists public.club_announcements (
  id uuid primary key default gen_random_uuid(),
  club_id text not null references public.club_profiles(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete restrict default auth.uid(),
  title text not null check (char_length(title) between 3 and 180),
  body text not null check (char_length(body) between 10 and 1200),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.club_memberships (
  club_id text not null references public.club_profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  application_id uuid references public.club_applications(id) on delete set null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  joined_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (club_id, user_id)
);

create table if not exists public.club_profile_views (
  id bigint generated by default as identity primary key,
  club_id text not null references public.club_profiles(id) on delete cascade,
  viewer_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  viewed_at timestamptz not null default now()
);

create index if not exists club_events_club_status_idx
  on public.club_events (club_id, status, starts_at);
create index if not exists club_announcements_club_status_idx
  on public.club_announcements (club_id, status, created_at desc);
create index if not exists club_views_club_date_idx
  on public.club_profile_views (club_id, viewed_at desc);
create index if not exists club_memberships_club_status_idx
  on public.club_memberships (club_id, status);

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'club_profiles', 'club_events', 'club_event_registrations',
    'club_announcements', 'club_memberships'
  ]
  loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format(
      'create trigger set_%I_updated_at before update on public.%I for each row execute procedure public.set_updated_at()',
      table_name,
      table_name
    );
  end loop;
end $$;

