create or replace function public.review_club_application(
  application_id uuid,
  decision text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target public.club_applications%rowtype;
begin
  if decision not in ('accepted', 'refused') then
    raise exception 'Décision invalide';
  end if;

  select * into target
  from public.club_applications
  where id = application_id;

  if target.id is null or not private.manages_club(target.club_id) then
    raise exception 'Accès refusé';
  end if;

  update public.club_applications
  set status = decision,
      reviewed_by = (select auth.uid()),
      reviewed_at = now(),
      updated_at = now()
  where id = application_id;

  if decision = 'accepted' then
    insert into public.club_memberships (club_id, user_id, application_id, status)
    values (target.club_id, target.applicant_id, target.id, 'active')
    on conflict (club_id, user_id) do update
      set status = 'active', application_id = excluded.application_id, updated_at = now();
  end if;

  insert into public.notifications (user_id, title, body, link)
  values (
    target.applicant_id,
    case when decision = 'accepted' then 'Candidature acceptée' else 'Mise à jour de votre candidature' end,
    case when decision = 'accepted'
      then 'Votre demande pour rejoindre le club a été acceptée.'
      else 'Votre demande n’a pas été retenue pour cette campagne.'
    end,
    '/clubs/' || target.club_id
  );
end;
$$;

revoke execute on function public.review_club_application(uuid, text) from public;
grant execute on function public.review_club_application(uuid, text) to authenticated;

create or replace function public.notify_club_members(
  target_club_id text,
  notification_title text,
  notification_body text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  sent_count integer;
begin
  if not private.manages_club(target_club_id) then
    raise exception 'Accès refusé';
  end if;
  if char_length(trim(notification_title)) < 3 or char_length(trim(notification_body)) < 5 then
    raise exception 'Notification incomplète';
  end if;

  insert into public.notifications (user_id, title, body, link)
  select user_id, trim(notification_title), trim(notification_body), '/clubs/' || target_club_id
  from public.club_memberships
  where club_id = target_club_id and status = 'active';

  get diagnostics sent_count = row_count;
  return sent_count;
end;
$$;

revoke execute on function public.notify_club_members(text, text, text) from public;
grant execute on function public.notify_club_members(text, text, text) to authenticated;

