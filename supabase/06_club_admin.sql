create or replace function private.manages_club(target_club_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.club_managers
    where user_id = (select auth.uid())
      and club_id = target_club_id
      and active = true
  ) or private.is_admin();
$$;

revoke execute on function private.manages_club(text) from public;
grant execute on function private.manages_club(text) to authenticated;

